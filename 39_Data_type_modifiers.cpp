#include <iostream>
using namespace std;

int main() {
    cout << sizeof(int) << endl;  // shows size of int byte which is 4 bits.
    cout << sizeof(long int) << endl;  // increase the size of bits  to 8 bits
    cout << sizeof(short int) << endl; // decrease the size of bits to 2 bits.
    cout << sizeof(long long) << endl;  // also increase but more high value than long.
}