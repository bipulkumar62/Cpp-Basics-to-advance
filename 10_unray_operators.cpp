// // increment(++) method

#include <iostream>
using namespace std;

int main() {
    int a = 10;

    int b = a++; // pehle kaam bd me update

    cout << a << endl;
    cout << b << endl;

    return 0;
}



#include <iostream>
using namespace std;

int main() {
    int a = 10;

    int b = ++a; // pehle update bd me kaam

    cout << a << endl;
    cout << b << endl;

    return 0;
}

// decrement (a--) is opposite of increment