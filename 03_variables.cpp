#include <iostream>
using namespace std;

int main() {
    int age = 25;       //int is the data type for integer values
    char grade = 'A';     //char is the data type for character values
    float height = 5.9;     //float is the data type for decimal values
    bool isStudent = true;     //bool is the data type for boolean values (true or false)
    double weight = 70.5;      //double is the data type for double precision decimal values
    
    cout << "Age: " << age << endl;         //cout used to print output to the console.
    cout << "Grade: " << grade << endl;         //cout used to print output to the console.
    cout << "Height: " << height << endl;            //cout used to print output to the console.
    cout << "Is Student: " << isStudent << endl;   //cout used to print output to the console.
    cout << "Weight: " << weight << endl;               //cout used to print output to the console.
    return 0;
}